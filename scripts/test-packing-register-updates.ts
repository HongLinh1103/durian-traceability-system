import assert from 'node:assert/strict';
import { createDemoState, GMP_GRADES, REGISTERS, saveRecord, gradeTotal, Values } from '../src/lib/processing-gmp';
import { upgradeReceivingGrades } from '../src/lib/receiving-reclassification';
import { clearLegacyReceivingNotes, editReceivingRecord } from '../src/lib/processing-receiving-edit';
import { certificateExtension, isCertificateLink } from '../src/lib/processing-certificate';
import { saveHarvestReceiving } from '../src/lib/processing-receiving';

let state = upgradeReceivingGrades(createDemoState(), 'test');
const original = state.records.receiving[0];
original.values.notes = 'Ghi chú cũ';
original.values.initialWeight = gradeTotal(original.values, 'grade') + Number(original.values.otherProcessing || 0) + Number(original.values.rejected || 0);
state = clearLegacyReceivingNotes(state);
assert.equal(state.records.receiving[0].values.notes, '—');
assert.equal(state.records.receiving[0].values.previousNotes, 'Ghi chú cũ');
assert.equal(original.values.notes, 'Ghi chú cũ');
assert.deepEqual(clearLegacyReceivingNotes(state), state);
const r = state.records.receiving[0];
const edit = (values: typeof r.values) => editReceivingRecord(state, r.id, values, 'test');
const edited = edit({ ...r.values, receiver: 'Người nhận mới', notes: ' ' });
assert.equal(edited.records.receiving[0].values.receiver, 'Người nhận mới');
assert.equal(edited.records.receiving[0].values.notes, '—');
assert.throws(() => edit({ ...r.values, grade1: 9999999 }), /sản xuất|vượt/);
assert.throws(() => editReceivingRecord(state, 'missing', r.values, 'test'), /Không tìm thấy/);
const withNote = edit({ ...r.values, notes: 'Ghi chú mới' });
assert.equal(clearLegacyReceivingNotes(withNote).records.receiving[0].values.notes, 'Ghi chú mới');

const draftState = structuredClone(state);
const draft = draftState.records.receiving[0];
draft.draft = true;
Object.assign(draft.values, { harvestRecordId: 'harvest-test', sourceEligible: '1', sourceConflict: '0', processingEligible: '1' });
const values: Values = { ...draft.values, notes: '' };
GMP_GRADES.forEach(g => { values['otherGrade' + g.key] = values['otherGrade' + g.key] || 0; });
const confirmed = saveHarvestReceiving(draftState, draft.id, values, true, '2026-10-25');
assert.equal(confirmed.records.receiving[0].values.notes, '—');
assert.equal(confirmed.records.receiving[0].values.date, values.date);
assert.throws(() => saveHarvestReceiving(draftState, draft.id, {...values, date: '2026-02-30'}, true, '2026-10-25'), /Ngày nhập hàng/);

const keys = REGISTERS.sales.fields.map(f => f.key);
for (const removed of ['truck','seal','departurePort','destinationPort']) assert(!keys.includes(removed));
assert.equal(keys[keys.indexOf('country') + 1], 'testCertificate');
const url = '/api/processing/gmp/certificates/12345678-1234-1234-1234-123456789abc.png';
assert(isCertificateLink(url));
assert(!isCertificateLink('javascript:alert(1)'));
assert(!isCertificateLink('/api/processing/gmp/certificates/../secret.png'));
assert.equal(certificateExtension(Uint8Array.from([137,80,78,71,13,10,26,10])), 'png');
assert.equal(certificateExtension(Uint8Array.from([255,216,255,0])), 'jpg');
assert.equal(certificateExtension(new TextEncoder().encode('<svg></svg>')), null);
state.records.aftersales = [];
state.payments = [];
const sales = state.records.sales[0];
assert.throws(() => saveRecord(state, 'sales', {id: sales.id, values: {...sales.values, testCertificate:'https://untrusted.example/file'}}, sales.id), /kiểm nghiệm/);
const saved = saveRecord(state, 'sales', {id: sales.id, values: {...sales.values, testCertificate:url}}, sales.id);
assert.equal(saved.records.sales.find(x => x.id === sales.id)!.values.testCertificate, url);
console.log('PASS: receiving edit, note default, source integrity, sales columns, certificate validation and persistence');
