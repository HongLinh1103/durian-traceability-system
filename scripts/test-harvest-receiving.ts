import assert from 'node:assert/strict';
import { emptyProcessingState, syncHarvestReceiving, saveHarvestReceiving, receivingProductionIntakes, HarvestReceivingSource } from '../src/lib/processing-receiving';
import { sources, saveRecord } from '../src/lib/processing-gmp';
import { buildRegisterDocx } from '../src/lib/processing-gmp-export';
import { populateReceivingSamples } from '../src/lib/processing-receiving-samples';
import { getReceivingRouteCodes } from '../src/components/processing/harvest-receiving';

async function main() {
    const harvest: HarvestReceivingSource = { id: 'h1', code: 'TH-2627-1510', ownerId: 'owner', facilityId: 'facility', status: 'WAITING_CONFIRMATION', date: '2026-10-15', season: '2026-2027', weight: 1000, seller: 'Nông dân A', phone: '0900000000', puc: 'VN-DNOR-001', origin: 'Vùng trồng A - Đồng Nai', variety: 'Ri6' };
    let state = syncHarvestReceiving(emptyProcessingState(), [harvest], 'owner', 'facility');
    const id = state.records.receiving[0].id;
    assert.equal(state.records.receiving[0].values.date, '');
    assert.equal(state.records.receiving[0].draft, true);
    assert.match(String(state.records.receiving[0].values.purchaseLotCode), /^TM-2026-1510/);
    const code = state.records.receiving[0].values.purchaseLotCode;
    assert.equal(syncHarvestReceiving(state, [{ ...harvest, code: 'TH-UPDATED' }], 'owner', 'facility').records.receiving[0].values.purchaseLotCode, code);
    assert.equal(sources(state, 'preprocessing').length, 0);
    assert.equal(syncHarvestReceiving(state, [harvest, harvest], 'owner', 'facility').records.receiving.length, 1);
    assert.equal(syncHarvestReceiving(emptyProcessingState(), [{ ...harvest, ownerId: 'other' }], 'owner', 'facility').records.receiving.length, 0);
    assert.equal(syncHarvestReceiving(emptyProcessingState(), [{ ...harvest, status: 'DRAFT' }], 'owner', 'facility').records.receiving.length, 0);
    state = syncHarvestReceiving(state, [{ ...harvest, weight: 1100, variety: 'Monthong' }], 'owner', 'facility');
    assert.equal(state.records.receiving[0].values.initialWeight, 1100);
    const input = { grade1: 600, grade2: 250, grade3: 100, gradeOther: 50, otherProcessing: 60, receiver: 'Người nhận A', processingEligible: '1', rejected: 999, initialWeight: 9999, seller: 'Giả mạo' };
    state = saveHarvestReceiving(state, id, input, false, '2026-10-15');
    assert.equal(state.records.receiving[0].values.acceptedWeight, 1060);
    assert.equal(state.records.receiving[0].values.unclassifiedWeight, 40);
    assert.equal(state.records.receiving[0].values.rejected, '');
    assert.equal(state.records.receiving[0].values.seller, harvest.seller);
    assert.equal(state.records.receiving[0].values.initialWeight, 1100);
    assert.throws(() => saveHarvestReceiving(state, id, { ...input, processingEligible: '0' }, true, '2026-10-15'), /an toàn thực phẩm/);
    assert.throws(() => saveHarvestReceiving(state, id, { ...input, grade1: 1600 }, true, '2026-10-15'), /vượt/);
    assert.throws(() => saveHarvestReceiving(state, id, { ...input, weightAdjustment: 20 }, true, '2026-10-15'), /lý do/);
    assert.throws(() => saveHarvestReceiving(state, id, { ...input, gradeOther: '' }, true, '2026-10-15'), /hoàn tất/);
    const adjusted = saveHarvestReceiving(state, id, { ...input, weightAdjustment: 10, weightDifferenceReason: 'Chênh lệch cân thực tế' }, true, '2026-10-15');
    assert.equal(adjusted.records.receiving[0].values.rejected, 50);
    state = saveHarvestReceiving(state, id, input, true, '2026-10-15');
    const received = state.records.receiving[0];
    assert.equal(received.values.date, '2026-10-15');
    assert.equal(received.values.rejected, 40);
    assert.equal(received.draft, false);
    assert.match(String(received.values.dgLotCodes), /^DG-/);
    assert.match(String(received.values.cbLotCodes), /^CB-/);
    assert.deepEqual(getReceivingRouteCodes(received, 'DG'), [String(received.values.dgLotCodes)]);
    assert.deepEqual(getReceivingRouteCodes(received, 'CB'), [String(received.values.cbLotCodes)]);
    const legacyRec = { ...received, values: { ...received.values, dgLotCodes: 'LH-2026-1510', cbLotCodes: 'LH-2026-1510' } };
    assert.deepEqual(getReceivingRouteCodes(legacyRec, 'DG'), ['DG-2026-1510']);
    assert.deepEqual(getReceivingRouteCodes(legacyRec, 'CB'), ['CB-2026-1510']);
    assert.equal(sources(state, 'preprocessing').length, 1);
    assert.deepEqual(receivingProductionIntakes(state).map(i => [i.route, i.weight]), [['fresh', 1000], ['other', 60]]);
    assert.throws(() => saveHarvestReceiving(state, id, input, true, '2026-10-15'), /đã xác nhận/);
    const conflict = syncHarvestReceiving(state, [{ ...harvest, weight: 1200 }], 'owner', 'facility');
    assert.equal(conflict.records.receiving[0].values.sourceConflict, '1');
    assert.equal(sources(conflict, 'preprocessing').length, 0);
    assert.equal(receivingProductionIntakes(conflict).length, 0);
    const cancelled = syncHarvestReceiving(state, [], 'owner', 'facility');
    assert.equal(cancelled.records.receiving.length, 1, 'Preserve confirmed traceability.');
    assert.equal(sources(cancelled, 'preprocessing').length, 0);
    const pending = syncHarvestReceiving(emptyProcessingState(), [harvest], 'owner', 'facility');
    assert.equal(syncHarvestReceiving(pending, [], 'owner', 'facility').records.receiving.length, 0);
    assert.throws(() => saveHarvestReceiving(emptyProcessingState(), 'manual', input, true, '2026-10-15'), /liên kết/);
    await buildRegisterDocx('receiving', [received], 'CƠ SỞ ĐÓNG GÓI');
    assert.equal(received.values.initialWeight, 1100);
    const sampled = populateReceivingSamples(state, 'owner', '2026-10-15');
    assert.equal(sampled.records.receiving.length, state.records.receiving.length + 1);
    assert.equal(sampled.records.receiving[0].values.initialWeight, received.values.initialWeight);
    assert.deepEqual(populateReceivingSamples(sampled, 'owner', '2026-10-15'), sampled);
    const sample = sampled.records.receiving.find(r => r.values.sampleSourceId)!;
    const savedSample = saveHarvestReceiving(sampled, sample.id, { grade1: 700, grade2: 200, grade3: 50, gradeOther: 0, otherProcessing: 20, processingEligible: '1', receiver: 'Người nhận mẫu', initialWeight: 99999 }, true, '2026-10-15');
    assert.equal(savedSample.records.receiving.find(r => r.id === sample.id)!.values.initialWeight, 1000);
    assert.equal(savedSample.records.receiving.find(r => r.id === sample.id)!.values.rejected, 30);
    console.log('PASS: harvest ownership/status, idempotent sync, immutable source, pending/confirmed weights, safety, weighing discrepancy, two production routes, conflicts, cancellation and Word export.');
}
main().catch(e => { console.error(e); process.exitCode = 1; });
