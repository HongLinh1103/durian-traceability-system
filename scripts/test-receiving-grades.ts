import assert from 'node:assert/strict';
import { createDemoState, gradeTotal } from '../src/lib/processing-gmp';
import { upgradeReceivingGrades } from '../src/lib/receiving-reclassification';
const state = createDemoState();
state.productionLots = [];
const record = state.records.receiving[0];
record.lotCode = 'LH-2026-0809';
record.values = { ...record.values, classificationComplete: '1', initialWeight: 1000, weightAdjustment: 0, grade1: 500, grade2: 100, grade3: 0, gradeOther: 0, otherProcessing: 100, rejected: 300 };
const next = upgradeReceivingGrades(state, 'test', true);
const v = next.records.receiving[0].values;
assert.equal(v.otherProcessing, 240);
assert.equal(v.rejected, 160);
assert.equal(v.acceptedWeight, 840);
assert.equal(gradeTotal(v, 'otherGrade'), 240);
assert.deepEqual(['1','2','3','Other'].map(key => v['otherGrade' + key]), [60,60,60,60]);
assert.equal(gradeTotal(v, 'grade') + gradeTotal(v, 'otherGrade') + Number(v.rejected), 1000);
assert.deepEqual(upgradeReceivingGrades(next, 'test', true), next);
assert.equal(state.records.receiving[0].values.rejected, 300);
const untouched = upgradeReceivingGrades(state, 'test');
assert.equal(untouched.records.receiving[0].values.rejected, 300);
console.log('PASS: receiving grade distribution, mass balance, scoped conversion, audit, idempotency');
