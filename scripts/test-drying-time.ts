import assert from 'node:assert/strict';
import { dryingTimestamp, dryingInput, dryingDuration, formatDryingTime } from '../src/lib/drying-time';
import { createDemoState, saveRecord, sources } from '../src/lib/processing-gmp';
import { displayValue } from '../src/lib/processing-gmp-export';
import { upgradeLegacyDryingDates } from '../src/lib/processing-drying-upgrade';

assert.equal(dryingTimestamp('2026-09-08T07:15'), '2026-09-08T00:15:00.000Z');
assert.equal(dryingInput('2026-09-08T00:15:00.000Z'), '2026-09-08T07:15');
assert.equal(formatDryingTime('2026-09-08T07:15'), '08/09/2026 07:15');
assert.equal(dryingDuration('2026-09-08T07:15', '2026-09-09T09:00'), '1 ngày 1 giờ 45 phút');
assert.equal(dryingDuration('2026-09-08T07:15', ''), 'Đang thực hiện');
assert.equal(dryingTimestamp('07:15'), '');
assert.equal(dryingTimestamp('2026-02-30T07:15'), '');
assert.equal(dryingTimestamp('2026-09-08T24:00'), '');
assert.match(formatDryingTime('07:15'), /Cần bổ sung ngày/);
assert.equal(displayValue({key:'dryStart',label:'',type:'datetime-local'}, '2026-09-08T07:15'), '08/09/2026 07:15');
const state=createDemoState();
const historical = createDemoState();
historical.records.preprocessing[0].values = { ...historical.records.preprocessing[0].values, date: '2026-09-08', dryStart: '07:15', dryEnd: '09:00' };
const upgraded = upgradeLegacyDryingDates(historical);
assert.equal(formatDryingTime(upgraded.records.preprocessing[0].values.dryStart), '08/09/2026 07:15');
assert.equal(formatDryingTime(upgraded.records.preprocessing[0].values.dryEnd), '08/09/2026 09:00');
assert.equal(upgraded.records.preprocessing[0].values.dryStartLegacyTime, '07:15');
assert.equal(historical.records.preprocessing[0].values.dryStart, '07:15');
assert.equal(upgradeLegacyDryingDates(upgraded), upgraded);
historical.records.preprocessing[0].values.dryEnd = '06:00';
assert.equal(upgradeLegacyDryingDates(historical), historical);
state.payments=[];
state.records.packaging=[];
const record=state.records.preprocessing[0];
const save=(dryStart:string,dryEnd:string)=>saveRecord(state,'preprocessing',{id:record.id,values:{...record.values,dryStart,dryEnd}},record.id);
assert.throws(()=>save('2026-09-08T07:15','2026-09-08T07:15'), /lớn hơn/);
assert.throws(()=>save('2026-09-08T07:15','2026-09-07T09:00'), /lớn hơn/);
assert.throws(()=>save('07:15','09:00'), /bổ sung/);
assert.throws(()=>save('',''), /bắt đầu/);
const ongoing=save('2026-09-08T07:15','');
assert(!sources(ongoing,'packaging').some(r=>r.id===record.id));
const complete=save('2026-09-08T07:15','2026-09-09T09:00');
assert.equal(complete.records.preprocessing.find(r=>r.id===record.id)!.values.dryEnd,'2026-09-09T02:00:00.000Z');
console.log('Drying datetime checks passed');
