import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { loadEnvConfig } from '@next/env';
import { readFileSync } from 'node:fs';
import { contactName,contactPhone,shipmentSchema,validateShipment,HandoverSnapshot } from '../src/lib/exporter-rules';

async function main(){
 assert.equal(contactPhone.parse('+84 912 345 678'),'+84912345678');
 assert.throws(()=>contactPhone.parse('Nam Ninh, Trung Quốc'));
 assert.throws(()=>contactName.parse('Công ty Xuất khẩu A'));
 assert.throws(()=>contactName.parse('0912345678'));
 assert.equal(contactName.parse('Nguyễn Văn A'),'Nguyễn Văn A');
 const draft=shipmentSchema.parse({status:'DRAFT',data:{},allocations:[]});
 validateShipment(draft,[]);
 assert.throws(()=>validateShipment({...draft,status:'CONFIRMED'},[]),/ít nhất/);
 assert.throws(()=>shipmentSchema.parse({status:'DRAFT',data:{actualDate:'2026-02-30'},allocations:[]}));
 const capacity=[{id:'a',acceptedBoxes:10,acceptedWeight:100,usedBoxes:4,usedWeight:40}];
 const valid={...draft,allocations:[{handoverId:'a',boxes:6,weight:60}]};
 validateShipment(valid,capacity);
 assert.throws(()=>validateShipment({...valid,allocations:[{handoverId:'a',boxes:7,weight:60}]},capacity),/vượt/);
 assert.throws(()=>validateShipment({...valid,allocations:[{handoverId:'a',boxes:6,weight:61}]},capacity),/vượt/);
 assert.throws(()=>validateShipment({...valid,allocations:[...valid.allocations,...valid.allocations]},capacity),/một lần/);
 assert.throws(()=>validateShipment(valid,[]),/không thuộc/);
 loadEnvConfig(process.cwd(),true);
 // Integration fixtures must never touch a configured remote/production database.
 const local=readFileSync('.env','utf8').match(/^DATABASE_URL\s*=\s*["']?([^"'\r\n]+)/m)?.[1];
 assert(local && ['localhost','127.0.0.1'].includes(new URL(local).hostname),'Exporter integration tests require a local database in .env');
 const integrationUrl=new URL(local);
 integrationUrl.searchParams.set('connection_limit','4');
 process.env.DATABASE_URL=integrationUrl.toString();
 const {prisma}=await import('../src/lib/prisma');
 const {acceptHandover,saveExporterShipment}=await import('../src/lib/exporter-service');
 const {publishedExportTrips}=await import('../src/lib/exporter-trace');
 const {publicProcessingTrace}=await import('../src/lib/processing-qr');
 const {certificateIdentities}=await import('../src/lib/certificate-access');
 const {createDemoState,saveRecord}=await import('../src/lib/processing-gmp');
 const pricing=createDemoState();
 pricing.records.aftersales=[];pricing.payments=[];
 const oldSale=pricing.records.sales[0];
 const businessValues={...oldSale.values,exporterId:'test-selected-exporter',customer:'Nguyễn Văn A',customerInfo:'0912345678',total:12345,price:''};
 const directValue=saveRecord(pricing,'sales',{id:oldSale.id,values:businessValues},oldSale.id);
 assert.equal(directValue.records.sales.find(r=>r.id===oldSale.id)!.values.total,12345);
 const optionalValue=saveRecord(pricing,'sales',{id:oldSale.id,values:{...businessValues,total:''}},oldSale.id);
 assert.equal(optionalValue.records.sales.find(r=>r.id===oldSale.id)!.values.total,0);
 assert.throws(()=>saveRecord(pricing,'sales',{id:oldSale.id,values:{...businessValues,total:'not-a-number'}},oldSale.id),/không âm/);
 assert.throws(()=>saveRecord(pricing,'sales',{id:oldSale.id,values:{...businessValues,price:'not-a-number'}},oldSale.id),/không âm/);
 const id='export-test-'+randomUUID();
 const orgA=id+'-a',orgB=id+'-b',actor=id+'-user',owner=id+'-packing',h1=id+'-h1',h2=id+'-h2';
 const snapshot:HandoverSnapshot={receiptCode:'XB-TEST',facilityName:'Test facility',facilityCode:'TEST',lotCode:id,variety:'Ri6',date:'2026-10-25',boxes:10,weight:100,grades:{quantity_boxes1:10,weight_kg1:100},certificate:'',country:'Trung Quốc',contactName:'Nguyễn Văn A',contactPhone:'0912345678'};
 try{
  await prisma.exporterOrganization.createMany({data:[{id:orgA,code:orgA,name:'Test Exporter A',contactName:'Test',phone:'0912345678',address:'Test'},{id:orgB,code:orgB,name:'Test Exporter B',contactName:'Test',phone:'0912345678',address:'Test'}]});
  await prisma.user.create({data:{id:actor,phone:id,password:'test-not-a-login',role:'EXPORTER',isApproved:true,accountStatus:'APPROVED',exporterOrganizationId:orgA}});
  assert.deepEqual(await certificateIdentities(actor,'EXPORTER'),['exporter:'+orgA]);
  await prisma.exporterHandover.createMany({data:[{id:h1,ownerId:owner,saleId:'sale1',exporterId:orgA,snapshot:JSON.parse(JSON.stringify(snapshot))},{id:h2,ownerId:owner+'-2',saleId:'sale2',exporterId:orgA,snapshot:JSON.parse(JSON.stringify(snapshot))}]});
  await assert.rejects(acceptHandover(orgB,actor,{id:h1,revision:0,boxes:10,weight:100,note:''}),/không tồn tại/);
  await assert.rejects(acceptHandover(orgA,actor,{id:h1,revision:0,boxes:11,weight:100,note:''}),/vượt/);
  await assert.rejects(acceptHandover(orgA,actor,{id:h1,revision:0,boxes:9,weight:90,note:''}),/chênh lệch/);
  await acceptHandover(orgA,actor,{id:h1,revision:0,boxes:9,weight:90,note:'Thiếu 1 thùng, 10 kg'});
  await acceptHandover(orgA,actor,{id:h2,revision:0,boxes:10,weight:100,note:''});
  await assert.rejects(acceptHandover(orgA,actor,{id:h1,revision:0,boxes:9,weight:90,note:'repeat'}),/đã được tiếp nhận/);
  await assert.rejects(saveExporterShipment(orgB,actor,{...draft,allocations:[{handoverId:h1,boxes:1,weight:10}]}),/không thuộc/);
  const first=await saveExporterShipment(orgA,actor,{...draft,allocations:[{handoverId:h1,boxes:4,weight:40},{handoverId:h2,boxes:5,weight:50}]});
  await assert.rejects(saveExporterShipment(orgA,actor,{...draft,allocations:[{handoverId:h1,boxes:6,weight:60}]}),/vượt/);
  const attempts=await Promise.allSettled([1,2].map(()=>saveExporterShipment(orgA,actor,{...draft,allocations:[{handoverId:h1,boxes:4,weight:40}]})));
  assert.equal(attempts.filter(r=>r.status==='fulfilled').length,1,'Concurrent allocations must not oversell');
  const cancelled=attempts.find(r=>r.status==='fulfilled') as PromiseFulfilledResult<Awaited<ReturnType<typeof saveExporterShipment>>>;
  await saveExporterShipment(orgA,actor,{...draft,id:cancelled.value.id,revision:cancelled.value.revision,status:'CANCELLED',allocations:[]});
  const full={...draft.data,carrier:'Transport',container:'TEST001',seal:'SEAL001',departurePort:'Cảng đi',destinationPort:'Cảng đến',country:'Trung Quốc',responsible:'Test'};
  const input={id:first.id,revision:first.revision,status:'CONFIRMED',isPublic:true,data:full,allocations:[{handoverId:h1,boxes:4,weight:40},{handoverId:h2,boxes:5,weight:50}]};
  const confirmed=await saveExporterShipment(orgA,actor,input);
  const corrected=await saveExporterShipment(orgA,actor,{...input,revision:confirmed.revision,data:{...full,seal:'CORRECTED'}});
  assert.equal((corrected.data as Record<string,string>).seal,'CORRECTED');
  await assert.rejects(saveExporterShipment(orgA,actor,{...input,revision:corrected.revision,allocations:[{handoverId:h1,boxes:3,weight:30}]}),/phân bổ/);
  const exported=await saveExporterShipment(orgA,actor,{...input,revision:corrected.revision,status:'EXPORTED',data:{...full,seal:'CORRECTED',actualDate:'2026-10-25'}});
  assert.equal(exported.status,'EXPORTED');
  const other=await saveExporterShipment(orgA,actor,{...draft,status:'CONFIRMED',isPublic:false,data:{...full,container:'PRIVATE'},allocations:[{handoverId:h1,boxes:1,weight:10}]});
  assert.equal(other.isPublic,false);
  const pub=await publishedExportTrips(owner,'sale1',id);
  assert.equal(pub.exportShipments.length,1);
  assert.equal(pub.exportShipments[0].container,'TEST001');
  assert.equal(pub.exportShipments[0].seal,'CORRECTED');
  assert.equal(pub.exportShipments[0].weight,40);
  const originSnapshot={demo:false,region:null,harvest:null,seller:{name:'Original facility',code:'ORIGINAL',address:'Original address'},sale:{id:'sale1',lot:id,variety:'Ri6',date:'2026-10-25',weight:100,boxes:10,customer:'Nguyễn Văn A',customerInfo:'0912345678',departurePort:'',destinationPort:'',truck:'',container:'',seal:''},logs:[]};
  await prisma.processingQrPublication.create({data:{token:id,ownerId:owner,saleId:'sale1',snapshot:originSnapshot}});
  const trace=await publicProcessingTrace(id);
  assert.equal(trace?.token,id);
  assert.equal(trace?.snapshot.seller.name,'Original facility');
  assert.equal(trace?.snapshot.exportShipments?.[0].container,'TEST001');
  assert.equal(trace?.snapshot.sale.container,'','Do not assign one trip to an entire source lot');
  const persisted=await prisma.processingQrPublication.findUniqueOrThrow({where:{token:id}});
  assert.deepEqual(persisted.snapshot,originSnapshot,'Do not replace origin snapshots or QR tokens');
  console.log('PASS: contact validation, tenant isolation, discrepancy receipt, multi-facility and multi-trip allocations, concurrent stock limits, draft cancellation, immutable confirmation, exporter publication and stable QR snapshots');
 }finally{
  await prisma.exporterShipmentAllocation.deleteMany({where:{handoverId:{in:[h1,h2]}}});
  await prisma.exporterShipment.deleteMany({where:{exporterId:{in:[orgA,orgB]}}});
  await prisma.exporterHandover.deleteMany({where:{id:{in:[h1,h2]}}});
  await prisma.processingQrPublication.deleteMany({where:{token:id}});
  await prisma.user.deleteMany({where:{id:actor}});
  await prisma.exporterOrganization.deleteMany({where:{id:{in:[orgA,orgB]}}});
  await prisma.$disconnect();
 }
}
main().catch(e=>{console.error(e);process.exitCode=1;});
