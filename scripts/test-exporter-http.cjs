  await prisma.partnerFacility.deleteMany({where:{ownerId:owner}});
  await prisma.user.deleteMany({where:{id:{in:[owner,userA,userB]}}});
  await prisma.exporterOrganization.deleteMany({where:{id:{in:[exporterA,exporterB]}}});
