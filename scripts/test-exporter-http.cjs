  const pack=await cookie(owner,'PROCESSING_FACILITY'),a=await cookie(userA,'EXPORTER'),b=await cookie(userB,'EXPORTER');
  async function request(url,cookie,body){return fetch(base+url,{method:body?'POST':'GET',headers:{Cookie:cookie,...(body?{'Content-Type':'application/json'}:{})},...(body?{body:JSON.stringify(body)}:{})});}
  let response=await request('/api/processing/gmp',pack);assert.equal(response.status,200,await response.clone().text());
