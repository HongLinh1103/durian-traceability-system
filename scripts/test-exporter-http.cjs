  await prisma.processingGmpWorkspace.update({where:{ownerId:owner},data:{revision:{increment:1}}});
  response=await request('/api/processing/gmp',pack,{action:'record',stage:'sales',revision:initial.revision,baseRecord:actual,record:{id:actual.id,values:{...actual.values,exporterId:exporterA,customer:'Nguyễn Văn A',customerInfo:'+84 912 345 678',testCertificate:certificate}}});
